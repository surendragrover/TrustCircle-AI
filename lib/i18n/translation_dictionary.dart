  static String translate(String key, String languageCode) {
    final code = languageCode.split('-').first;
    final termIndex = _termIndexes[key];
    if (termIndex != null) {
      return (_verdicts[code] ?? _verdicts['en']!)[termIndex];
    }
    return _labels[code]?[key] ?? _labels['en']?[key] ?? 'Text unavailable';
  }

  static bool hasAllVerdicts(String languageCode) {
    final code = languageCode.split('-').first;
    return _termIndexes.keys.every(
      (key) => translate(key, code) != 'Text unavailable',
    );
  }
